ResponsePlace _station(
  String name,
  TerritorialGroup group, {
  int activeNeeds = 0,
}) {
  return ResponsePlace(
    id: '${group.name}-${name.toLowerCase().replaceAll(' ', '-')}',
    name: name,
    type: ResponsePlaceType.sdisStation,
    group: group,
    activeNeeds: activeNeeds,
  );
}

